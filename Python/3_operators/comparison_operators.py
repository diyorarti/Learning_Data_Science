# Comparison operators: ==, !=, >, <, >=, <=, compartion operators return boolean value
a = 10
b = 5
print(f"num 1: {a}")
print(f"num 2: {b}")
print(f"Equal {a==b}") 
print(f"Not equal {a!=b}") 
print(f"Greater than {a>b}") 
print(f"Less than {a<b}") 
print(f"Greater or equal {a>=b}") 
print(f"Less or equal {a<=b}") 
