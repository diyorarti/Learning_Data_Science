# Arithmetic operators: +, -, *, /, // (floor divition), % (modulus), ** (power)

num1 = 20
num2 = 5

# Addition 
addition = num1 + num2
print(f"Addition: {addition}")

# Substraction 
substraction = num1 - num2
print(f"Substraction: {substraction}")

# Multiplication 
multiplication = num1 * num2
print(f"Multiplication: {multiplication}")

# Divition 
divition = num2 / num1
print(f"Divition: {divition}")

# Floor Divition
floor_divition = num2 / 3
print(f'Floor Divition: {floor_divition}')

# Modulus 
modulus = num1 / 15
print(f'Modulus: {modulus}')

# Power 
power = num1 ** num2
print(f"Power: {power}")