"""
Python has 3 main numeric data types
1 - Whole numbers 
2 - Float numbers
3 - Complex
"""

# Whole numbers 
num1 = 23
num2 = 40 
sum_whole_numbers = num1 + num2
print(f"sum of whole numbers {sum_whole_numbers}")

# Float numbers
num3 = 3.10
num4 = 45.60
multiplication = num3 * num4
print(multiplication)

# Complex numbers wiht a real + imaginary part
c1 = 2 + 4j
c2 = -1 * 4j
divition = c1 / c2
print(divition)

